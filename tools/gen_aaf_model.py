"""Generates src/aaf_model_data.inc (the AAF baseline object model: classes, properties, types)
from the model tables of pyaaf2 (https://github.com/markreidvfx/pyaaf2, MIT license, see
third_party/pyaaf2-model/LICENSE). The tables describe the public AAF object specification.

usage: python tools/gen_aaf_model.py <pyaaf2>/src/aaf2 src/aaf_model_data.inc
"""
import os
import runpy
import sys


def q(s):
    return '"%s"' % s if s is not None else "nullptr"


def main():
    src, out = sys.argv[1], sys.argv[2]
    classes = runpy.run_path(os.path.join(src, "model", "classdefs.py"))["classdefs"]
    types = runpy.run_path(os.path.join(src, "model", "typedefs.py"))
    # the Root class and its two reference types live in metadict.py
    root_classes = {
        "Root": ("b3b398a5-1c90-11d4-8053-080036210804", None, True, {
            "Header": ("0d010301-0102-0100-060e-2b3401010102", 0x0002, "05022800-0000-0000-060e-2b3401040101", False, False),
            "MetaDictionary": ("0d010301-0101-0100-060e-2b3401010102", 0x0001, "05022700-0000-0000-060e-2b3401040101", False, False),
        })
    }
    root_types = {
        "HeaderStrongRefence": ("05022800-0000-0000-060e-2b3401040101", "0d010101-0101-2f00-060e-2b3402060101"),
        "MetaDictionaryStrongReference": ("05022700-0000-0000-060e-2b3401040101", "0d010101-0225-0000-060e-2b3402060101"),
    }

    lines = []
    w = lines.append
    w("// Generated by tools/gen_aaf_model.py from pyaaf2's model tables (MIT license,")
    w("// third_party/pyaaf2-model/LICENSE) - do not edit.")
    w("// clang-format off")
    w("")

    allclasses = dict(root_classes)
    allclasses.update(classes)
    names = []
    for name, (auid, parent, concrete, props) in allclasses.items():
        ident = "kProps_" + name
        names.append((name, auid, parent, concrete, ident, len(props)))
        if props:
            w("static const AafPropModel %s[] = {" % ident)
            for pname, (pauid, pid, ptype, optional, unique) in props.items():
                w("  {%s, %s, 0x%04x, %s, %s, %s}," % (q(pname), q(pauid.lower()), pid or 0, q(ptype.lower()),
                                                        "true" if optional else "false", "true" if unique else "false"))
            w("};")
    w("")
    w("static const AafClassModel kAafClasses[] = {")
    for name, auid, parent, concrete, ident, n in names:
        w("  {%s, %s, %s, %s, %s, %d}," % (q(name), q(auid.lower()), q(parent.lower() if parent else None),
                                          "true" if concrete else "false", ident if n else "nullptr", n))
    w("};")
    w("")

    tdefs = []  # (name, auid, kind, element, size, signed, listIdent, count)
    lists = []

    def strlist(ident, values):
        lists.append("static const char* const %s[] = {%s};" % (ident, ", ".join(q(v) for v in values)))

    for name, (auid, size, signed) in types["ints"].items():
        tdefs.append((name, auid, "kInt", None, size, signed, None, None, 0))
    for name, (auid, elem, values) in types["enums"].items():
        keys = sorted(values.keys())
        strlist("kEnumNames_" + name, [values[k] for k in keys])
        lists.append("static const int64_t kEnumValues_%s[] = {%s};" % (name, ", ".join(str(k) for k in keys)))
        tdefs.append((name, auid, "kEnum", elem, 0, False, "kEnumNames_" + name, "kEnumValues_" + name, len(keys)))
    for name, (auid, members) in types["records"].items():
        strlist("kRecordNames_" + name, [m[0] for m in members])
        strlist("kRecordTypes_" + name, [m[1].lower() for m in members])
        tdefs.append((name, auid, "kRecord", None, 0, False, "kRecordNames_" + name, "kRecordTypes_" + name, len(members)))
    for name, (auid, elem, count) in types["fixed_arrays"].items():
        tdefs.append((name, auid, "kFixedArray", elem, count, False, None, None, 0))
    for name, (auid, elem) in types["var_arrays"].items():
        tdefs.append((name, auid, "kVarArray", elem, 0, False, None, None, 0))
    for name, (auid, renamed) in types["renames"].items():
        tdefs.append((name, auid, "kRename", renamed, 0, False, None, None, 0))
    for name, (auid, elem) in types["strings"].items():
        tdefs.append((name, auid, "kString", elem, 0, False, None, None, 0))
    for name, auid in types["streams"].items():
        tdefs.append((name, auid, "kStream", None, 0, False, None, None, 0))
    for name, auid in types["opaques"].items():
        tdefs.append((name, auid, "kOpaque", None, 0, False, None, None, 0))
    for name, (auid, values) in types["extenums"].items():
        keys = list(values.keys())
        strlist("kExtEnumNames_" + name, [values[k] for k in keys])
        strlist("kExtEnumValues_" + name, [k.lower() for k in keys])
        tdefs.append((name, auid, "kExtEnum", None, 0, False, "kExtEnumNames_" + name, "kExtEnumValues_" + name, len(keys)))
    for name, auid in types["chars"].items():
        tdefs.append((name, auid, "kCharacter", None, 0, False, None, None, 0))
    for name, auid in types["indirects"].items():
        tdefs.append((name, auid, "kIndirect", None, 0, False, None, None, 0))
    for name, (auid, elem) in types["sets"].items():
        tdefs.append((name, auid, "kSet", elem, 0, False, None, None, 0))
    srefs = dict(types["strongrefs"])
    srefs.update(root_types)
    for name, (auid, ref) in srefs.items():
        tdefs.append((name, auid, "kStrongRef", ref, 0, False, None, None, 0))
    for name, (auid, ref, path) in types["weakrefs"].items():
        strlist("kWeakPath_" + name, [p.lower() for p in path])
        tdefs.append((name, auid, "kWeakRef", ref, 0, False, "kWeakPath_" + name, None, len(path)))

    for l in lists:
        w(l)
    w("")
    w("static const AafTypeModel kAafTypes[] = {")
    for name, auid, kind, elem, size, signed, l1, l2, n in tdefs:
        w("  {%s, %s, AafTypeModel::%s, %s, %d, %s, %s, %s, %d}," % (
            q(name), q(auid.lower()), kind, q(elem.lower() if elem else None), size,
            "true" if signed else "false", l1 or "nullptr", l2 or "nullptr", n))
    w("};")
    w("// clang-format on")

    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
